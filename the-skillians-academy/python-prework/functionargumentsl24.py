""" WHAT ARE FUNCTION ARGUMENTS """

""" 	- function arguments are the values which we pass into a function when we are calling a fucntion

	- in the example below name is a parameter and the word Harshita is the function argument
"""

#the value which we pass when we are calling a function are called as function arguments
#variables in function definition are called function parameters
#creating a function is also known as defining a function

def greet(name):
	print("Hello!", name)

greet("Harshita")



